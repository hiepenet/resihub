/// Khớp một bản ghi tài khoản ngân hàng (`{ bank_name, bank_code, bank_bin }`) với danh mục VietQR.
Map<String, dynamic>? matchVietQrBank(List<dynamic>? banks, Map<String, dynamic>? paymentAccount) {
  if (paymentAccount == null || banks == null || banks.isEmpty) return null;

  final code = (paymentAccount['bank_code'] ?? '').toString().trim().toUpperCase();
  final bin = (paymentAccount['bank_bin'] ?? '').toString().trim();
  final nameLower = (paymentAccount['bank_name'] ?? '').toString().trim().toLowerCase();

  for (final raw in banks) {
    if (raw is! Map) continue;
    final bk = Map<String, dynamic>.from(raw);
    final bkCode = (bk['code'] ?? '').toString().trim().toUpperCase();
    final bkBin = (bk['bin'] ?? '').toString().trim();
    final bkShort = (bk['shortName'] ?? bk['short_name'] ?? '').toString().trim().toLowerCase();
    final bkFull = (bk['name'] ?? '').toString().trim().toLowerCase();

    if (code.isNotEmpty && bkCode == code) return bk;
    if (bin.isNotEmpty && bkBin == bin) return bk;
    if (nameLower.isNotEmpty) {
      if (bkShort == nameLower) return bk;
      if (bkCode.toLowerCase() == nameLower) return bk;
      if (bkFull == nameLower) return bk;
    }
  }

  return null;
}

/// Chuyển danh sách ngân hàng VietQR thành mảng `options` giàu thông tin cho component Dropdown/Select.
/// Nếu hồ sơ hiện tại lưu tên ngân hàng cũ ngoài danh mục VietQR, tự động chèn lên đầu danh sách.
List<Map<String, dynamic>> buildVietQrBankOptions(
  List<dynamic>? banks, [
  Map<String, dynamic>? currentBankInfo,
]) {
  final List<Map<String, dynamic>> mapped = [];
  final list = banks ?? const [];

  for (final raw in list) {
    if (raw is! Map) continue;
    final b = Map<String, dynamic>.from(raw);
    final shortName = (b['shortName'] ?? b['short_name'] ?? b['code'] ?? b['name'] ?? '').toString();
    final code = b['code']?.toString() ?? '';
    final bin = b['bin']?.toString() ?? '';
    final name = b['name']?.toString() ?? '';
    final logo = b['logo']?.toString() ?? '';

    mapped.add({
      'value': shortName,
      'label': code.isNotEmpty ? '$shortName ($code)' : shortName,
      'sublabel': name,
      'badge': bin.isNotEmpty ? 'BIN $bin' : '',
      'logo': logo,
      'searchText': '$shortName $code $bin $name',
      'bank': b,
    });
  }

  final cur = (currentBankInfo?['bank_name'] ?? '').toString().trim();
  final matched = matchVietQrBank(banks, currentBankInfo);
  if (cur.isNotEmpty && matched == null && !mapped.any((o) => o['value'] == cur)) {
    final curBin = currentBankInfo?['bank_bin']?.toString() ?? '';
    final curCode = currentBankInfo?['bank_code']?.toString() ?? '';
    final curLogo = currentBankInfo?['bank_logo']?.toString() ?? '';

    mapped.insert(0, {
      'value': cur,
      'label': cur,
      'sublabel': 'Ngân hàng hiện tại',
      'badge': curBin.isNotEmpty ? 'BIN $curBin' : '',
      'logo': curLogo,
      'searchText': '$cur $curCode $curBin',
      'bank': null,
    });
  }

  return mapped;
}
